  private runCompactLabyrinth(size: number, sizeY: number = size): void {
    const SOLID = true, OPEN = false;
    const w = size, h = sizeY, s = Math.min(w, h);

    this.maze = Array(w).fill(null).map(() => Array(h).fill(SOLID));
    this.width = w;
    this.height = h;

    for (let i = 0; i < w; i++) {
      this.maze[i][0] = OPEN;
      this.maze[i][h - 1] = OPEN;
    }
    for (let i = 0; i < h; i++) {
      this.maze[0][i] = OPEN;
      this.maze[w - 1][i] = OPEN;
    }

    const borderInset = Math.max(2, Math.round(s * 0.0625));
    const cornerSize  = Math.max(3, Math.round(s * 0.125));
    const centerHalf  = Math.max(4, Math.round(s * 0.125));
    const cx = w >> 1;
    const cy = h >> 1;

    this._carveRect(borderInset, borderInset,
                    borderInset + cornerSize, borderInset + cornerSize);
    this._carveRect(w - borderInset - cornerSize, borderInset,
                    w - borderInset, borderInset + cornerSize);
    this._carveRect(borderInset, h - borderInset - cornerSize,
                    borderInset + cornerSize, h - borderInset);
    this._carveRect(w - borderInset - cornerSize, h - borderInset - cornerSize,
                    w - borderInset, h - borderInset);
    this._carveRect(cx - centerHalf, cy - centerHalf,
                    cx + centerHalf, cy + centerHalf);

    for (let x = 1; x < w - 1; x++) this.maze[x][cy] = OPEN;
    for (let y = 1; y < h - 1; y++) this.maze[cx][y] = OPEN;
  }

  private _carveRect(x1: number, y1: number, x2: number, y2: number): void {
    const xa = Math.max(0, x1), xb = Math.min(this.width, x2);
    const ya = Math.max(0, y1), yb = Math.min(this.height, y2);
    for (let x = xa; x < xb; x++) {
      for (let y = ya; y < yb; y++) {
        this.maze[x][y] = false;
      }
    }
  }

