function mulberry32(seed: number): () => number {
  let a = seed | 0;
  return function () {
    a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export interface MazeSquare {
  x: number;
  y: number;
  size: number;
}

class MazeZone {
  array: (boolean | number)[][];
  offset: { x: number; y: number };
  length: number;

  constructor(
    array: (boolean | number)[][] = [],
    offset = { x: 0, y: 0 },
    length?: number
  ) {
    this.array = array;
    this.offset = offset;
    this.length = length ?? array.reduce((sum, row) => sum + row.filter(r => r).length, 0);
  }

  get width(): number { return this.array.length; }
  get height(): number { return this.array.length === 0 ? 0 : this.array[0].length; }

  normalize(): this {
    while (this.array.length > 0 && this.array[0].every(r => !r)) {
      this.offset.x++;
      this.array.shift();
    }
    while (this.array.length > 0 && this.array[this.array.length - 1].every(r => !r)) {
      this.array.pop();
    }
    let minY = Infinity;
    let maxY = -Infinity;
    for (let x = 0; x < this.width; x++) {
      for (let y = 0; y < this.height; y++) {
        if (!this.array[x][y]) continue;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
    this.offset.y += minY;
    if (minY === Infinity) {
      this.array = [];
    } else {
      this.array = this.array.map(row => row.slice(minY, maxY + 1));
    }
    return this;
  }

  blocks(): MazeSquare[] {
    const blocks: MazeSquare[] = [];
    for (let x = 0; x < this.width; x++)
      for (let y = 0; y < this.height; y++)
        if (this.array[x][y])
          blocks.push({ x: x + this.offset.x, y: y + this.offset.y, size: 1 });
    return blocks;
  }

  shaveSingles(): [MazeZone | null, MazeSquare[]] | null {
    const { width, height } = this;
    if (this.length <= 3)
      return [null, this.blocks()];

    const output: MazeSquare[] = [];
    let shaveable = true;
    let shaved = false;
    while (shaveable) {
      shaveable = false;
      for (let x = 0; x < width; x++) {
        for (let y = 0; y < height; y++) {
          if (!this.array[x][y]) continue;
          const left = x > 0 && this.array[x - 1][y];
          const right = x + 1 < width && this.array[x + 1][y];
          const top = y > 0 && this.array[x][y - 1];
          const bottom = y + 1 < height && this.array[x][y + 1];
          if ((!left && !right) || (!top && !bottom)) {
            this.array[x][y] = false;
            output.push({ x: x + this.offset.x, y: y + this.offset.y, size: 1 });
            shaveable = true;
          }
        }
      }
      shaved = shaved || shaveable;
    }
    this.length -= output.length;
    if (shaved)
      return [this.normalize(), output];
    return null;
  }

  takeBiggestSquare(): MazeSquare | null {
    const { width, height } = this;
    let best: { x: number; y: number } | null = null;
    let maxSize = 0;
    for (let x = 0; x < width; x++) {
      for (let y = 0; y < height; y++) {
        if (!this.array[x][y]) continue;
        let size = 1;
        loop: while (x + size < width && y + size < height) {
          for (let i = 0; i <= size; i++)
            if (!this.array[x + size][y + i] || !this.array[x + i][y + size])
              break loop;
          size++;
        }
        if (size > maxSize) {
          maxSize = size;
          best = { x, y };
        }
      }
    }
    if (!best) return null;
    this.length -= maxSize * maxSize;
    for (let x = 0; x < maxSize; x++) {
      for (let y = 0; y < maxSize; y++) {
        this.array[best.x + x][best.y + y] = false;
      }
    }
    const square: MazeSquare = { x: best.x + this.offset.x, y: best.y + this.offset.y, size: maxSize };
    if (best.x === 0 || best.x + maxSize === width
      || best.y === 0 || best.y + maxSize === height)
      this.normalize();
    return square;
  }

  shave(): [MazeZone | null, MazeSquare[]] {
    this.normalize();
    const shaveResult = this.shaveSingles();
    if (shaveResult)
      return shaveResult;
    const biggestSquare = this.takeBiggestSquare();
    return [this.width && this.height ? this : null, biggestSquare ? [biggestSquare] : []];
  }

  intoSquares(): MazeSquare[] {
    let current: MazeZone | null = this as MazeZone;
    const squares: MazeSquare[] = [];
    while (current) {
      const now = current.shave();
      current = now[0];
      squares.push(...now[1]);
    }
    return squares;
  }
}

