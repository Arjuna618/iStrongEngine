const GROW_MIN_DENSITY = 0.6;

export function growTemplateRows(rows: readonly string[], targetW: number, targetH: number): { rows: string[]; area: number } {
  const count = (ls: readonly string[]) => { let n = 0; for (const l of ls) for (let i = 0; i < l.length; i++) if (l.charCodeAt(i) === 64) n++; return n; };
  const before = count(rows);
  const growAxis = (lines: string[], target: number): string[] => {
    const n0 = lines.length;
    let need = target - n0;
    if (need <= 0 || n0 < 3) return lines;
    const runs: { a: number; b: number; dens: number }[] = [];
    for (let i = 1; i < n0 - 1; ) {
      let j = i;
      while (j + 1 < n0 - 1 && lines[j + 1] === lines[i]) j++;
      const l = lines[i];
      let at = 0, fixed = false;
      for (let k = 1; k < l.length - 1; k++) { const ch = l.charCodeAt(k); if (ch === 64) at++; else if (ch === 35) fixed = true; }
      runs.push({ a: i, b: j, dens: fixed ? 0 : (l.length > 2 ? at / (l.length - 2) : 0) });
      i = j + 1;
    }
    let maxD = 0;
    for (const r of runs) if (r.dens >= GROW_MIN_DENSITY && r.dens > maxD) maxD = r.dens;
    const cand = runs.filter(r => r.dens >= GROW_MIN_DENSITY && r.dens >= maxD - 0.05);
    if (cand.length === 0) return lines;
    const groups: { members: number[]; len: number; self: boolean }[] = [];
    const taken = new Set<number>();
    for (let i = 0; i < cand.length; i++) {
      if (taken.has(i)) continue;
      const r = cand[i];
      const ma = n0 - 1 - r.b, mb = n0 - 1 - r.a;
      let m = -1;
      for (let k = i; k < cand.length; k++) if (!taken.has(k) && cand[k].a === ma && cand[k].b === mb) { m = k; break; }
      taken.add(i);
      if (m === i) groups.push({ members: [i], len: r.b - r.a + 1, self: true });
      else if (m >= 0) { taken.add(m); groups.push({ members: [i, m], len: 2 * (r.b - r.a + 1), self: false }); }
      else groups.push({ members: [i], len: r.b - r.a + 1, self: true });
    }
    const hasSelf = groups.some(g => g.self);
    if (!hasSelf && need % 2 === 1) need--;
    if (need <= 0) return lines;
    const total = groups.reduce((s, g) => s + g.len, 0);
    const share = groups.map(g => {
      const exact = (need * g.len) / total;
      let base = Math.floor(exact);
      if (!g.self && base % 2 === 1) base--;
      return { g, base, rem: exact - base };
    });
    let left = need - share.reduce((s, x) => s + x.base, 0);
    const order = share.map((x, i) => i).sort((p, q) => (share[q].rem - share[p].rem) || (p - q));
    for (let pass = 0; left > 0 && pass < 4; pass++) {
      for (const i of order) {
        if (left <= 0) break;
        const step = share[i].g.self ? 1 : 2;
        if (step > left) continue;
        share[i].base += step;
        left -= step;
      }
    }
    const extra = new Map<number, number>();
    for (const x of share) {
      if (x.g.members.length === 2) { extra.set(cand[x.g.members[0]].a, x.base / 2); extra.set(cand[x.g.members[1]].a, x.base / 2); }
      else extra.set(cand[x.g.members[0]].a, x.base);
    }
    const out: string[] = [];
    for (let i = 0; i < n0; i++) {
      out.push(lines[i]);
      const e = extra.get(i);
      if (e) for (let k = 0; k < e; k++) out.push(lines[i]);
    }
    return out;
  };
  let grown = growAxis([...rows], targetH);
  const w0 = grown[0]?.length ?? 0;
  if (targetW > w0) {
    const cols: string[] = [];
    for (let x = 0; x < w0; x++) { let c = ''; for (let y = 0; y < grown.length; y++) c += grown[y][x]; cols.push(c); }
    const gc = growAxis(cols, targetW);
    if (gc.length !== cols.length) {
      const back: string[] = [];
      for (let y = 0; y < grown.length; y++) { let r = ''; for (let x = 0; x < gc.length; x++) r += gc[x][y]; back.push(r); }
      grown = back;
    }
  }
  const after = count(grown);
  return { rows: grown, area: before > 0 ? after / before : 1 };
}

