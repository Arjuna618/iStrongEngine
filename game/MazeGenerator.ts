  private _ensureLabyrinthCenterReachable(): void {
    const w = this.width, h = this.height;
    if (w !== 128 || h !== 128) return;

    const N = w * h;

    const visited = new Uint8Array(N);
    const bfsQueue = new Int32Array(N);
    let bfsHead = 0, bfsTail = 0;
    for (let x = 0; x < w; x++) {
      for (let y = 0; y < h; y++) {
        if (!this.maze[x][y] && (x === 0 || x === w - 1 || y === 0 || y === h - 1)) {
          const idx = x * h + y;
          if (!visited[idx]) {
            visited[idx] = 1;
            bfsQueue[bfsTail++] = idx;
          }
        }
      }
    }
    while (bfsHead < bfsTail) {
      const idx = bfsQueue[bfsHead++];
      const cx = (idx / h) | 0;
      const cy = idx - cx * h;
      if (cx > 0 && !this.maze[cx - 1][cy] && !visited[(cx - 1) * h + cy]) {
        visited[(cx - 1) * h + cy] = 1;
        bfsQueue[bfsTail++] = (cx - 1) * h + cy;
      }
      if (cx < w - 1 && !this.maze[cx + 1][cy] && !visited[(cx + 1) * h + cy]) {
        visited[(cx + 1) * h + cy] = 1;
        bfsQueue[bfsTail++] = (cx + 1) * h + cy;
      }
      if (cy > 0 && !this.maze[cx][cy - 1] && !visited[cx * h + cy - 1]) {
        visited[cx * h + cy - 1] = 1;
        bfsQueue[bfsTail++] = cx * h + cy - 1;
      }
      if (cy < h - 1 && !this.maze[cx][cy + 1] && !visited[cx * h + cy + 1]) {
        visited[cx * h + cy + 1] = 1;
        bfsQueue[bfsTail++] = cx * h + cy + 1;
      }
    }

    let anchorX = -1, anchorY = -1;
    for (let r = 0; r < 32 && anchorX < 0; r++) {
      for (let dx = -r; dx <= r && anchorX < 0; dx++) {
        for (let dy = -r; dy <= r && anchorX < 0; dy++) {
          if (Math.abs(dx) !== r && Math.abs(dy) !== r) continue;
          const x = 64 + dx, y = 64 + dy;
          if (x < 0 || x >= w || y < 0 || y >= h) continue;
          if (!this.maze[x][y]) { anchorX = x; anchorY = y; }
        }
      }
    }
    if (anchorX < 0) return;

    const anchorIdx = anchorX * h + anchorY;
    if (visited[anchorIdx]) return;
    const parent = new Int32Array(N);
    parent.fill(-1);
    const dist = new Int32Array(N);
    dist.fill(0x7fffffff);
    const processed = new Uint8Array(N);

    const DQ_CAP = N * 8;
    const DQ_MID = N * 4;
    const dq = new Int32Array(DQ_CAP);
    let dqFront = DQ_MID, dqBack = DQ_MID;

    for (let i = 0; i < N; i++) {
      if (visited[i]) {
        dist[i] = 0;
        dq[dqBack++] = i;
      }
    }

    while (dqFront < dqBack) {
      const u = dq[dqFront++];
      if (processed[u]) continue;
      processed[u] = 1;
      if (u === anchorIdx) break;
      const ux = (u / h) | 0;
      const uy = u - ux * h;
      const du = dist[u];

      if (ux > 0) {
        const v = (ux - 1) * h + uy;
        if (!processed[v]) {
          const cost = this.maze[ux - 1][uy] ? 1 : 0;
          const dv = du + cost;
          if (dv < dist[v]) {
            dist[v] = dv;
            parent[v] = u;
            if (cost === 0) dq[--dqFront] = v;
            else dq[dqBack++] = v;
          }
        }
      }
      if (ux < w - 1) {
        const v = (ux + 1) * h + uy;
        if (!processed[v]) {
          const cost = this.maze[ux + 1][uy] ? 1 : 0;
          const dv = du + cost;
          if (dv < dist[v]) {
            dist[v] = dv;
            parent[v] = u;
            if (cost === 0) dq[--dqFront] = v;
            else dq[dqBack++] = v;
          }
        }
      }
      if (uy > 0) {
        const v = ux * h + (uy - 1);
        if (!processed[v]) {
          const cost = this.maze[ux][uy - 1] ? 1 : 0;
          const dv = du + cost;
          if (dv < dist[v]) {
            dist[v] = dv;
            parent[v] = u;
            if (cost === 0) dq[--dqFront] = v;
            else dq[dqBack++] = v;
          }
        }
      }
      if (uy < h - 1) {
        const v = ux * h + (uy + 1);
        if (!processed[v]) {
          const cost = this.maze[ux][uy + 1] ? 1 : 0;
          const dv = du + cost;
          if (dv < dist[v]) {
            dist[v] = dv;
            parent[v] = u;
            if (cost === 0) dq[--dqFront] = v;
            else dq[dqBack++] = v;
          }
        }
      }
    }

    if (parent[anchorIdx] === -1) return;

    const carveCells: number[] = [];
    let cur = anchorIdx;
    while (cur !== -1 && !visited[cur]) {
      const cx = (cur / h) | 0;
      const cy = cur - cx * h;
      if (this.maze[cx][cy]) carveCells.push(cur);
      cur = parent[cur];
    }

    const size = w - 1;
    if (this.staticRand < 0.5) {
      for (let i = 0; i < carveCells.length; i++) {
        const cell = carveCells[i];
        const x = (cell / h) | 0;
        const y = cell - x * h;
        this.maze[x][y] = false;
        this.maze[x][size - y] = false;
        this.maze[size - x][y] = false;
        this.maze[size - x][size - y] = false;
      }
    } else {
      for (let i = 0; i < carveCells.length; i++) {
        const cell = carveCells[i];
        const x = (cell / h) | 0;
        const y = cell - x * h;
        this.maze[x][y] = false;
        this.maze[y][size - x] = false;
        this.maze[size - x][size - y] = false;
        this.maze[size - y][x] = false;
      }
    }
  }

